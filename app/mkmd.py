    a('')
    a('## How it computes')
    a('1. `FLOW_ROUTING RASPIPE` hands dynamic wave link and node updates to `raspipe.c`. Hydrology, controls, quality, statistics and the .out format stay EPA\'s.')
    a('2. Each conduit is cut into cells of `RASPIPE_CELL_LENGTH` (default 100 ft), at most `RASPIPE_MAX_CELLS` (20). Levels live in cells, flows on faces. A junction cell borrows the end piece of each pipe that meets it.')
    a('3. Each cell has a volume table V(eta) from SWMM\'s own cross-section geometry, flat level in a sloping cell. dV/deta = T is split into running sums of rises and falls, T = T1 - T2, V = V1 - V2 (Casulli and Stelling 2013). Above a closed crown V is constant and the level is crown + P/gamma: no slot.')
    a('4. Cell balance: V(eta_new) = V_old + dt * (sum of face flows in - out + lateral). Face flow: diffusion wave (default; friction balances the water surface slope, steady flow is Manning) or full shallow water (`RASPIPE_EQUATIONS SWE`, HEC\'s Eulerian-Lagrangian advection). Pressure term weighted by theta (`RASPIPE_THETA`, default 1.0).')
    a('5. The network is one sparse M-matrix, factored by LDL^T with minimum degree ordering. Plain Newton first; on failure, nested Newton on V1 and V2 (outer loop m, inner loop k).')
    a('6. Pipe steps run inside the SWMM routing step at a target residence time Courant number (`RASPIPE_COURANT`, 0.9, HEC\'s default): C = dt * outflow / volume.')
    a('7. Engine 1.3 adds `RASPIPE_PRESSURE_AREA` (default 0): each full cell stores this plan area per unit head above its crown (`raspipe.c:1395` `tabSplit(t, RasPipePressArea * p->barrels)`), and each junction cell the same per barrel of the highest pipe it borrows from (`raspipe.c:1366-1367`). Parsed in `project.c:800`, converted to internal ft2 in `dynwave.c:198`. 12.566 ft2 is what HEC-RAS 7.0.2 held on EXTRAN 1.')
