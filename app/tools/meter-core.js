  // where strings and comments are already blank. A '<' opens JSX only where an expression may start.
  function jsxTextRanges(s) {
    const out = [], n = s.length;
    const idStart = c => /[A-Za-z_$]/.test(c || '');
    const KW = /(^|[^\w$])(return|yield|default|case|else|do|in|of|typeof|void|await)$/;
    function exprCtx(i) {
      let j = i - 1; while (j >= 0 && /\s/.test(s[j])) j--;
      if (j < 0) return true;
      const c = s[j];
      if ('(,=?:{[!&|;}'.includes(c)) return !(c === '=' && s[j - 1] === '=' ) && !(c === '=' && s[j - 1] === '!');
      if (c === '>' && s[j - 1] === '=') return true;                        // => <div>
      return KW.test(s.slice(Math.max(0, j - 8), j + 1));
    }
    function braceEnd(j) {                    // s[j] === '{'; scans nested JSX inside the expression
      let depth = 0;
      for (let k = j; k < n; k++) {
        const c = s[k];
        if (c === '{') depth++;
        else if (c === '}') { depth--; if (depth === 0) return k + 1; }
        else if (c === '<' && (idStart(s[k + 1]) || s[k + 1] === '>') && exprCtx(k)) { const r = element(k); if (r > 0) k = r - 1; }
      }
      return -1;
    }
    function element(i) {
      const mark = out.length;
      const fail = () => { out.length = mark; return -1; };
      let j = i + 1;
      if (s[j] !== '>') {
        const nm = /^[A-Za-z_$][\w$.:-]*/.exec(s.slice(j, j + 80)); if (!nm) return fail(); j += nm[0].length;
        for (;;) {
          while (j < n && /\s/.test(s[j])) j++;
          if (s[j] === '/' && s[j + 1] === '>') return j + 2;
          if (s[j] === '>') { j++; break; }
          if (s[j] === '{') { j = braceEnd(j); if (j < 0) return fail(); continue; }
          const an = /^[A-Za-z_$][\w$:.-]*/.exec(s.slice(j, j + 80)); if (!an) return fail(); j += an[0].length;
          while (j < n && /\s/.test(s[j])) j++;
          if (s[j] !== '=') continue;
          j++; while (j < n && /\s/.test(s[j])) j++;
          if (s[j] === '"' || s[j] === "'") { const q = s.indexOf(s[j], j + 1); if (q < 0) return fail(); j = q + 1; }
          else if (s[j] === '{') { j = braceEnd(j); if (j < 0) return fail(); }
          else return fail();
        }
      } else j++;
      for (;;) {                               // children
        const t0 = j;
        while (j < n && s[j] !== '<' && s[j] !== '{') j++;
        if (j > t0 && /[A-Za-z0-9]/.test(s.slice(t0, j))) out.push([t0, j]);
        if (j >= n) return fail();
        if (s[j] === '{') { j = braceEnd(j); if (j < 0) return fail(); continue; }
        if (s[j + 1] === '/') { const k = s.indexOf('>', j); if (k < 0) return fail(); return k + 1; }
        if (!(idStart(s[j + 1]) || s[j + 1] === '>')) return fail();
        const r = element(j); if (r < 0) return fail(); j = r;
      }
    }
    for (let i = 0; i < n; i++) {
      if (s[i] === '<' && (idStart(s[i + 1]) || s[i + 1] === '>') && exprCtx(i)) { const r = element(i); if (r > 0) i = r - 1; }
    }
    return out;
  }
