  // A long line is an embedded payload only if it looks like encoded data, not code
  function isDataLine(L) {
    if (/data:[\w/+.-]+;base64,[A-Za-z0-9+/=]{500,}/.test(L)) return true;
    const sample = L.length > 4000 ? L.slice(0, 2000) + L.slice(-2000) : L;
    const b64 = (sample.match(/[A-Za-z0-9+/=]/g) || []).length;
    if (b64 / sample.length > 0.97 && !/[(){};]/.test(sample.slice(100, -100))) return true;
    // inlined JSON data: dense with quotes, free of control flow
    const quotes = (sample.match(/"/g) || []).length;
    const bare = sample.replace(/"(?:[^"\\]|\\.)*"/g, '""');      // keywords inside strings are just words
    return quotes / sample.length > 0.06 && !/\b(function|return|if|for|while|switch)\b|=>/.test(bare);
  }

