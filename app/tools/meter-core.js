  // FNV-1a hash over text with carriage returns removed; the length is the normalized length,
  // so an LF copy and a CRLF copy of the same file hash identically.
  function hashText(s) {
    let h1 = 0x811c9dc5, h2 = 0x01000193, len = 0;
    for (let i = 0; i < s.length; i++) {
      const c = s.charCodeAt(i);
      if (c === 13) continue;
      len++;
      h1 = Math.imul(h1 ^ c, 16777619) >>> 0;
      h2 = Math.imul(h2 ^ c, 2246822519) >>> 0;
    }
    return h1.toString(16) + ':' + h2.toString(16) + ':' + len;
  }
  // A /*! banner marks a library build only when it names a known library, or the file is minified.
