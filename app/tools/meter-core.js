  // Halstead operators include each language's keywords; everything else that is a name or a number is an operand
  const HAL_KEYWORDS = new Set(('if else elif elsif for foreach while do loop until repeat switch case default break continue return goto try catch except finally throw throws raise ' +
    'function def fn func fun sub lambda class struct enum union interface trait impl module namespace package program subroutine procedure begin end then endif enddo call ' +
    'import from export use using include require extern static const let var val mut pub public private protected internal virtual override final abstract async await yield ' +
    'new delete sizeof typeof instanceof in is not and or with as pass none null nil true false self this super void int long short char float double bool boolean string unsigned signed auto ' +
    'integer real logical character complex dimension parameter allocate deallocate select where type typedef inline volatile register template typename operator friend match when unless rescue ensure').split(' '));
  // cognitive-complexity style: a branch costs 1 plus how deeply it is nested inside its routine; && and || cost 1 flat
  const LOGICAL_AT = /^(?:&&|\|\||and\b|or\b|\.and\.|\.or\.|-and\b|-or\b)/i;

  // per-routine decision points, nesting, duplicated windows and relative imports, gathered file by file
  // maintainability index of one routine (Oman and Hagemeister, rescaled 0-100 as Visual Studio does)
  function routineMI(lineToks, l0, l1, cc) {
    const ops = new Set(), opds = new Set(); let N1 = 0, N2 = 0, loc = 0;
    for (let k = l0; k <= l1; k++) { const tm = lineToks[k]; if (!tm) continue; loc++;
      for (const t of tm) { const c = t.charCodeAt(0), word = (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || c === 95 || c === 36;
        if ((word && !HAL_KEYWORDS.has(t.toLowerCase())) || (c >= 48 && c <= 57)) { N2++; opds.add(t); } else { N1++; ops.add(t); } } }
    if (!loc) return null;
    const V = (N1 + N2) * Math.log2(Math.max(2, ops.size + opds.size));
    return Math.max(0, Math.min(100, (171 - 5.2 * Math.log(Math.max(1, V)) - 0.23 * cc - 16.2 * Math.log(loc)) * 100 / 171));
  }
  function collectStructure(L, SL, fam, lang, decPos, acc, ctx, spans0, lineToks) {
    const S = acc.st, s = L.stripped;
    const NLs = []; for (let k = s.indexOf('\n'); k >= 0; k = s.indexOf('\n', k + 1)) NLs.push(k);
    const lineOf = pos => { let lo = 0, hi = NLs.length; while (lo < hi) { const mid = (lo + hi) >> 1; if (NLs[mid] < pos) lo = mid + 1; else hi = mid; } return lo + 1 + (ctx.line0 || 0); };
    const spans = spans0.slice().sort((a, b) => a.start - b.start || b.end - a.end);
    // nesting at a position: braces for brace languages, indentation for Python, none for Fortran and Pascal
    let OB = null, CB = null, IND = null, STEP = 4;
    const cnt = (arr, p) => { let lo = 0, hi = arr.length; while (lo < hi) { const mid = (lo + hi) >> 1; if (arr[mid] < p) lo = mid + 1; else hi = mid; } return lo; };
    const depthAt = p => { if (!OB) { OB = []; CB = []; for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); if (c === 123) OB.push(i); else if (c === 125) CB.push(i); } } return cnt(OB, p) - cnt(CB, p); };
    const indentAt = p => { if (!IND) { IND = s.split('\n').map(l => /\S/.test(l) ? l.match(/^[ \t]*/)[0].replace(/\t/g, '    ').length : -1); const diffs = new Set(); for (let i = 1; i < IND.length; i++) if (IND[i] > 0 && IND[i - 1] >= 0 && IND[i] > IND[i - 1]) diffs.add(IND[i] - IND[i - 1]); STEP = diffs.size ? Math.min(...diffs) : 4; } return IND[lineOf(p) - 1 - (ctx.line0 || 0)] || 0; };
    const nestOf = (p, r) => {
      if (fam === 'js' || fam === 'c') return Math.max(0, depthAt(p) - depthAt(r.start) - 1);
      if (fam === 'py') return Math.max(0, Math.round((indentAt(p) - indentAt(r.at) - STEP) / STEP));
      return 0;
    };
    const cogOf = (p, r) => LOGICAL_AT.test(s.slice(p, p + 5)) ? 1 : 1 + (r ? nestOf(p, r) : 0);
    if (spans.length) {
      const dc = new Array(spans.length).fill(0), cg = new Array(spans.length).fill(0), stack = []; let si = 0;
      for (const p of decPos) {
        while (si < spans.length && spans[si].start <= p) { while (stack.length && spans[stack[stack.length - 1]].end < spans[si].start) stack.pop(); stack.push(si++); }
        while (stack.length && spans[stack[stack.length - 1]].end < p) stack.pop();
        if (stack.length) { const ri = stack[stack.length - 1]; dc[ri]++; cg[ri] += cogOf(p, spans[ri]); } else { S.outside++; S.cogTotal += 1; }
      }
      for (const v of cg) { S.cog.push(v); S.cogTotal += v; }
      const loc0 = p => lineOf(p) - 1 - (ctx.line0 || 0);
      if (lineToks) spans.forEach((r, i) => { const mi = routineMI(lineToks, loc0(r.at), loc0(r.end), dc[i] + 1); if (mi != null) S.mi.push(mi); });
      spans.forEach((r, i) => {
        const cc = dc[i] + 1; S.cc.push(cc);
        if (S.worst.length < 10 || cc > S.worst[S.worst.length - 1].cc) { S.worst.push({ path: ctx.path, line: lineOf(r.at), name: r.name.slice(0, 60), cc }); S.worst.sort((a, b) => b.cc - a.cc); if (S.worst.length > 10) S.worst.length = 10; }
        if (r.nest != null) { S.nested++; if (r.nest > S.nestMax) S.nestMax = r.nest;
          if (S.nestWorst.length < 5 || r.nest > S.nestWorst[S.nestWorst.length - 1].nest) { S.nestWorst.push({ path: ctx.path, line: lineOf(r.at), name: r.name.slice(0, 60), nest: r.nest }); S.nestWorst.sort((a, b) => b.nest - a.nest); if (S.nestWorst.length > 5) S.nestWorst.length = 5; } }
      });
    } else { S.outside += decPos.length; S.cogTotal += decPos.length; }
    // duplicated code: windows of DUP_WINDOW consecutive substantial code lines, hashed after whitespace is collapsed
    const kept = [];
    for (let k = 0; k < L.lines; k++) if (L.lineCode[k]) { const n = (SL[k] || '').trim().replace(/\s+/g, ' '); if (n.length >= 10 && (n.match(TOKEN_RE) || []).length >= 4) kept.push(n); }
    S.considered += kept.length;
    if (kept.length >= DUP_WINDOW) {
      const part = { marks: new Uint8Array(kept.length) }; S.parts.push(part);
      for (let i = 0; i + DUP_WINDOW <= kept.length; i++) {
        const w = kept.slice(i, i + DUP_WINDOW).join('\n'), key = fnv(w, 2166136261) * 2097152 + (fnv(w, 33554467) & 2097151);
        const prev = S.windows.get(key);
        if (prev === undefined) { S.windows.set(key, [S.parts.length - 1, i]); continue; }
        if (prev[0] === S.parts.length - 1 && i - prev[1] < DUP_WINDOW) continue;   // a window overlapping its own first copy
        part.marks.fill(1, i, i + DUP_WINDOW); S.parts[prev[0]].marks.fill(1, prev[1], prev[1] + DUP_WINDOW);
      }
    }
    // the project's own imports, for cycles (JavaScript/TypeScript and Python relative imports)
    if (fam === 'js') {
      const re = /(?:\bfrom\s*|\bimport\s*\(?\s*|\brequire\s*\(\s*)['"](\.{1,2}\/[^'"\n]*|[@~]\/[^'"\n]*)['"]/g; let m;
      while ((m = re.exec(L.noComments))) S.rel.push(m[1][0] === '.' ? { from: ctx.path, js: m[1] } : { from: ctx.path, alias: m[1].slice(2) });   // @/x and ~/x: the project's own path alias
    } else if (fam === 'c' && /^(?:C|C\+\+|CUDA)$/.test(lang)) {
      const re = /^[ \t]*#[ \t]*include[ \t]*"([^"\n]+)"/gm; let m;
      while ((m = re.exec(L.noComments))) S.rel.push({ from: ctx.path, inc: m[1] });
    } else if (fam === 'c' && lang === 'Rust') {
      const re = /^[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?mod[ \t]+([A-Za-z_]\w*)[ \t]*;/gm; let m;      // mod x; -> x.rs or x/mod.rs beside it
      while ((m = re.exec(s))) S.rel.push({ from: ctx.path, rmod: m[1] });
    } else if (fam === 'py') {
      const re = /^[ \t]*from[ \t]+(\.+)([\w.]*)[ \t]+import[ \t]+\(?([\w, \t*]+)/gm; let m;
      while ((m = re.exec(L.noComments))) S.rel.push({ from: ctx.path, dots: m[1].length, mod: m[2], names: m[3].split(',').map(x => x.trim().split(/\s+/)[0]).filter(x => x && x !== '*') });
      const ab = /^[ \t]*(?:from[ \t]+([A-Za-z_][\w.]*)[ \t]+import[ \t]+\(?([\w, \t*]+)|import[ \t]+([A-Za-z_][\w.]*(?:[ \t]*,[ \t]*[A-Za-z_][\w.]*)*))/gm;   // absolute imports of the project's own modules
      while ((m = ab.exec(L.noComments))) {
        if (m[1]) S.rel.push({ from: ctx.path, pyabs: m[1], names: m[2].split(',').map(x => x.trim().split(/\s+/)[0]).filter(x => x && x !== '*') });
        else for (const mod of m[3].split(',').map(x => x.trim())) S.rel.push({ from: ctx.path, pyabs: mod });
      }
    } else if (fam === 'f90' || fam === 'f77') {
      const re = /^[ \t]*use[ \t]*(?:,[ \t]*\w+[ \t]*::)?[ \t]*(\w+)/gim; let m;
      while ((m = re.exec(s))) S.rel.push({ from: ctx.path, fuse: m[1].toLowerCase() });
      const dm = /^[ \t]*module[ \t]+(?!procedure\b)(\w+)/gim;
      while ((m = dm.exec(s))) S.fmods.set(m[1].toLowerCase(), ctx.path);
    }
  }
  function importCycles(paths, rel, fmods) {
    const norm = p => { const o = []; for (const x of p.split('/')) { if (!x || x === '.') continue; if (x === '..') o.pop(); else o.push(x); } return o.join('/'); };
    const dirOf = p => p.split('/').slice(0, -1).join('/');
    const JSX = ['', '.js', '.mjs', '.cjs', '.jsx', '.ts', '.tsx', '.mts', '/index.js', '/index.ts', '/index.jsx', '/index.tsx', '/index.mjs'];
    const pick = c => c.find(x => paths.has(x));
    let byBase = null, pyIdx = null;
    const findInc = (from, spec) => {
      const direct = norm(dirOf(from) + '/' + spec); if (paths.has(direct)) return direct;
      if (!byBase) { byBase = new Map(); for (const p of paths) { const b = p.split('/').pop().toLowerCase(); if (!byBase.has(b)) byBase.set(b, []); byBase.get(b).push(p); } }
      const tail = spec.toLowerCase(), c = byBase.get(tail.split('/').pop()) || [];
      return c.find(p => p.toLowerCase().endsWith('/' + tail)) || c[0];
    };
    const edges = new Map(); let nEdges = 0;
    const add = (a, b) => { if (!b || a === b) return; if (!edges.has(a)) edges.set(a, new Set()); if (!edges.get(a).has(b)) { edges.get(a).add(b); nEdges++; } };
    for (const r of rel) {
      if (r.js) { const b = norm(dirOf(r.from) + '/' + r.js); add(r.from, pick(JSX.map(e => b + e))); continue; }
      if (r.inc) { add(r.from, findInc(r.from, r.inc)); continue; }
      if (r.alias != null) { const root = r.from.split('/')[0]; let hit; for (const e of JSX) { for (const p of paths) if (p.split('/')[0] === root && (p.endsWith('/src/' + r.alias + e) || p.endsWith('/' + r.alias + e))) { hit = p; break; } if (hit) break; } add(r.from, hit); continue; }
      if (r.rmod) { const d = dirOf(r.from), base = /(?:^|\/)(?:main|lib|mod)\.rs$/.test(r.from) ? d : d + '/' + r.from.split('/').pop().replace(/\.rs$/, ''); add(r.from, pick([d + '/' + r.rmod + '.rs', d + '/' + r.rmod + '/mod.rs', base + '/' + r.rmod + '.rs'])); continue; }
      if (r.fuse) { add(r.from, fmods && fmods.get(r.fuse)); continue; }
      if (r.pyabs) {
        const segs = r.pyabs.split('.'), want = segs.join('/');
        if (!pyIdx) { pyIdx = new Map(); for (const p of paths) if (/\.pyx?$/.test(p)) { const k = p.replace(/\.pyx?$/, '').replace(/\/__init__$/, ''); const parts = k.split('/'); for (let i = 0; i < parts.length; i++) { const t = parts.slice(i).join('/'); if (!pyIdx.has(t)) pyIdx.set(t, []); pyIdx.get(t).push(p); } } }
        const near = c => c.find(p => p.split('/')[0] === r.from.split('/')[0]) || c[0];
        let hit = false;
        for (const nm of r.names || []) { const c = pyIdx.get(want + '/' + nm); if (c) { add(r.from, near(c)); hit = true; } }   // from pkg import module
        if (!hit) for (let n = segs.length; n >= 1; n--) { const c = pyIdx.get(segs.slice(0, n).join('/')); if (c) { add(r.from, near(c)); break; } }
        continue;
      }
      let d = dirOf(r.from).split('/'); d = d.slice(0, Math.max(0, d.length - (r.dots - 1))); const dir = d.join('/');
      if (r.mod) { const b = (dir ? dir + '/' : '') + r.mod.replace(/\./g, '/'); add(r.from, pick([b + '.py', b + '.pyx', b + '/__init__.py'])); }
      else for (const n of r.names) { const b = (dir ? dir + '/' : '') + n; add(r.from, pick([b + '.py', b + '.pyx', b + '/__init__.py'])); }
    }
    // Tarjan's strongly connected components; a component of two or more files is a cycle
    let idx = 0; const ix = new Map(), low = new Map(), on = new Set(), st = [], comps = [];
    const visit = v => {
      ix.set(v, idx); low.set(v, idx); idx++; st.push(v); on.add(v);
      for (const w of edges.get(v) || []) { if (!ix.has(w)) { visit(w); low.set(v, Math.min(low.get(v), low.get(w))); } else if (on.has(w)) low.set(v, Math.min(low.get(v), ix.get(w))); }
      if (low.get(v) === ix.get(v)) { const c = []; let w; do { w = st.pop(); on.delete(w); c.push(w); } while (w !== v); if (c.length > 1) comps.push(c.sort()); }
    };
    for (const v of edges.keys()) if (!ix.has(v)) visit(v);
    comps.sort((a, b) => b.length - a.length);
    let maxOut = 0, maxFile = null; for (const [f, set] of edges) if (set.size > maxOut) { maxOut = set.size; maxFile = f; }
    return { edges: nEdges, graphFiles: edges.size, cycles: comps.length, filesInCycles: comps.reduce((t, c) => t + c.length, 0), sample: comps.slice(0, 5).map(c => c.slice(0, 8)), maxOut, maxFile };
  }
