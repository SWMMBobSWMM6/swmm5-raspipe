  const POINTS_PER_DECADE = 25;

  // A dimension the code does not have at all scores 0. Otherwise: 100 at the anchor,
  // +/- ppd points for every factor of ten above or below it, never below 0.
  // v1.3: the hard floor (score 0 below one ten-thousandth of the anchor) is replaced by a soft one. The curve is
  // log10(1 + x/x0), scaled so HydroCouple is exactly 100, where x0 is the count at which the hard scale hit 0.
  // Above about a hundredth of the anchor the two agree to a tenth of a point; below, small counts no longer all score 0.
  // floor: 'soft' (baseline d on) or 'hard' (baselines a, b, c, so old reports keep their old scores).
  function dimScore(x, anchor, ppd, floor) {
    if (!(x > 0)) return 0;
    const p = ppd || POINTS_PER_DECADE, a = Math.max(anchor, 1e-9);
    if (floor === 'hard') return Math.max(0, 100 + p * Math.log10(x / a));
    const x0 = a * Math.pow(10, -100 / p);
    return 100 * Math.log10(1 + x / x0) / Math.log10(1 + a / x0);
  }
  // Four sub-indexes on the same scale: size, structure, test evidence and SWMM vocabulary are read separately
  const GROUPS = [
    { key: 'size', name: 'Size', dims: ['bulk', 'routines'], what: 'How much code there is: tokens and callable units.' },
    { key: 'structure', name: 'Structure', dims: ['branches', 'stack', 'dependencies', 'formats'], what: 'How tangled and how wide: decision points, languages and technologies, outside libraries, file formats.' },
    { key: 'tests', name: 'Test evidence', dims: ['checks'], what: 'Test declarations and assertions present in the source.' },
    { key: 'swmm', name: 'SWMM vocabulary', dims: ['swmm'], what: 'SWMM 5.2.4 terms used in code.' }
  ];
  function grade(measure, anchor, weights, ppd, floor) {
    const rows = DIMENSIONS.map(d => {
      const w = weights && weights[d.key] != null ? weights[d.key] : d.weight;
      const v = measure[d.key] || 0;
      return { key: d.key, name: d.name, value: v, anchor: anchor[d.key], ratio: anchor[d.key] > 0 ? v / anchor[d.key] : 0, score: dimScore(v, anchor[d.key], ppd, floor), weight: w };
    });
    const groups = {};
    for (const g of GROUPS) {
      const rs = rows.filter(r => g.dims.includes(r.key)), ws = rs.reduce((s, r) => s + r.weight, 0);
      groups[g.key] = ws > 0 ? rs.reduce((s, r) => s + r.weight * r.score, 0) / ws : null;
    }
    const wsum = rows.reduce((s, r) => s + r.weight, 0);
    if (!(wsum > 0)) return { total: null, invalid: true, rows, groups };
    return { total: rows.reduce((s, r) => s + r.weight * r.score, 0) / wsum, rows, groups };
  }

