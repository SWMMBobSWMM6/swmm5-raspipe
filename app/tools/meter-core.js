  const nonWs = s => { let c = 0; for (let i = 0; i < s.length; i++) { const ch = s.charCodeAt(i); if (ch !== 32 && ch !== 9 && ch !== 13) c++; } return c; };
  // Lines that carry comment text, among lines that carry anything. A Python triple-quoted string that stands alone
  // as a statement (a docstring) counts as comment, as line counters such as scc and cloc count it.
  function commentLinesOf(code, L, fam) {
    const raw = code.split('\n'), nc = L.noComments.split('\n'), st = fam === 'py' ? L.stripped.split('\n') : null;
    let comment = 0, text = 0, open = null, doc = false;
    for (let k = 0; k < raw.length; k++) {
      const r = raw[k], a = nc[k] || '', n = nonWs(r);
      let isC = n > 0 && nonWs(a) < n;
      if (st) {
        let at = 0, lineDoc = !!(open && doc);
        for (;;) {
          if (open) { const j = a.indexOf(open, at); if (j < 0) break; at = j + 3; open = null; }
          else {
            const q1 = a.indexOf('"""', at), q2 = a.indexOf("'''", at), q = q1 < 0 ? q2 : q2 < 0 ? q1 : Math.min(q1, q2); if (q < 0) break;
            open = a.substr(q, 3); doc = /^[rRuUbB]{0,2}$/.test((st[k] || '').slice(0, q).trim()); if (doc) lineDoc = true; at = q + 3;
          }
        }
        if (lineDoc && n > 0) isC = true;
      }
      if (!n) continue;
      text++; if (isC) comment++;
    }
    return { comment, text };
  }
