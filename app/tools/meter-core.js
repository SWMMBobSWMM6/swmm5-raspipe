  const VERSIONED = /\bv?\d+\.\d+(?:\.\d+)?\b/;
  function looksMinified(text) { const lines = text.split('\n').length; return text.length / lines > 250; }
  function bannerOf(text) { const m = text.match(/^\s*\/\*![\s\S]*?\*\//); return m ? m[0].slice(0, 600) : null; }
  function libraryBuildReason(text) {
    const b = bannerOf(text); if (!b) return null;
    const k = b.match(KNOWN_BANNER) || text.slice(0, 600).match(KNOWN_BANNER);
    if (k) return 'banner names a known library (' + k[0] + ')';
    if (looksMinified(text) && VERSIONED.test(b)) return 'minified build with a versioned /*! banner';
    return null;
  }
