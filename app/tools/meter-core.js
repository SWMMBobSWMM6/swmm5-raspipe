  // Resolve the project's own modules per language, so they are not counted as outside libraries
  function buildResolver(files) {
    const byBase = new Map(), pyMods = new Set(), pasUnits = new Set(), rustMods = new Set(), fMods = new Set(), segs = new Set(), stems = new Set();
    const pyDirs = new Map(), pyInit = new Set();     // folder name -> parent paths of folders holding .py files (PEP 420)
    const first = new Set(files.map(f => f.path.includes('/') ? f.path.split('/')[0].toLowerCase() : ''));
    const rootSeg = first.size === 1 ? Array.from(first)[0] : '';
    for (const f of files) {
      const p = f.path.toLowerCase(), parts = p.split('/'), base = parts[parts.length - 1], stem = base.replace(/\.[^.]+$/, '');
      if (!byBase.has(base)) byBase.set(base, []); byBase.get(base).push(p);
      for (const s of parts.slice(0, -1)) segs.add(s);
      stems.add(stem);
      if (/\.pyx?$/.test(base)) {
        if (base === '__init__.py') { if (parts.length > 1) { pyMods.add(parts[parts.length - 2]); pyInit.add(parts.slice(0, -1).join('/')); } } else pyMods.add(stem);
        if (parts.length > 1) { const nm = parts[parts.length - 2], parent = parts.slice(0, -2).join('/'); if (!pyDirs.has(nm)) pyDirs.set(nm, new Set()); pyDirs.get(nm).add(parent); }
      }
      if (/\.(pas|pp|dpr|lpr)$/.test(base)) pasUnits.add(stem);
      if (base.endsWith('.rs')) { rustMods.add(stem === 'mod' && parts.length > 1 ? parts[parts.length - 2] : stem); const si = parts.lastIndexOf('src'); if ((stem === 'lib' || stem === 'main') && si > 0) rustMods.add(parts[si - 1].replace(/-/g, '_')); }
      if (f.text && /\.(f90|f95|f03|f08|f|for|fpp)$/i.test(f.path)) { const re = /^[ \t]*module[ \t]+(?!procedure\b)(\w+)/gim; let m; while ((m = re.exec(f.text))) fMods.add(m[1].toLowerCase()); }
    }
    return {
      py: n => pyMods.has(n), pas: n => pasUnits.has(n),
      // PEP 420: a folder of .py files without __init__.py is still the project's own package when it sits at the
      // project root, under src/, or beside or above the importing file. It never hides a well-known installed package.
      pyNs: (n, from) => {
        const ps = pyDirs.get(n); if (!ps) return false;
        const dir = (from || '').toLowerCase().split('/').slice(0, -1).join('/');
        for (const P of ps) {
          if (PY_KNOWN.has(n) && !pyInit.has(P ? P + '/' + n : n)) continue;
          if (P === '' || P === rootSeg || /(^|\/)src$/.test(P) || dir === P || dir.startsWith(P + '/')) return true;
        }
        return false;
      }, rust: n => rustMods.has(n), f: n => fMods.has(n),
      seg: n => n !== 'std' && n !== 'core' && (segs.has(n) || stems.has(n)),
      c: h => { const hl = h.toLowerCase(), b = hl.split('/').pop(), c = byBase.get(b); return !!c && c.some(p => p === hl || p.endsWith('/' + hl)); }
    };
  }

  // files: [{path, text}] ; returns measurement + per-file table + exclusion log
  function analyzeSet(files, opts) {
    opts = opts || {};
    const acc = newAcc();
    const excluded = { vendored: [], generated: [], duplicate: [], doxygen: [], binary: [], user: [], unknown: 0, reasons: {} };
    const suspects = [];
    const forceIn = new Set(opts.include || []), forceOut = new Set(opts.exclude || []);
    const setRoot = commonRoot(files.map(f => f.path));
    const setAside = (list, path, reason, item) => { list.push(item === undefined ? path : item); excluded.reasons[path] = reason; };
    const perFile = [];
    const doxyDirs = new Set();
    for (const f of files) {
      if (DOXY_SIG.test(f.path)) doxyDirs.add(f.path.replace(/\/[^/]*$/, ''));
      else if (/\.html?$/i.test(f.path) && f.text && /Generated by Doxygen/i.test(f.text.slice(0, 3000))) doxyDirs.add(f.path.replace(/\/[^/]*$/, ''));
    }
    const inDoxy = p => { for (const d of doxyDirs) if (p === d || p.startsWith(d + '/')) return true; return false; };
    const I = buildResolver(files);
    // vendored-folder names are tested below the folder the user chose, so the root never gets an app thrown out
    const firstSegs = new Set(files.map(f => f.path.includes('/') ? f.path.split('/')[0] : ''));
    const root = firstSegs.size === 1 && !firstSegs.has('') ? Array.from(firstSegs)[0] + '/' : '';
    const seen = new Map();
    let fi = 0;
    for (const f of files) {
      if (opts.onProgress && (fi++ % 25 === 0)) opts.onProgress(fi, files.length);
      const path = f.path, text = f.text;
      if (text == null) continue;
      const base = path.split('/').pop();
      const cls = classify(path, text);
      if (!cls) { excluded.unknown++; continue; }
      if (text.indexOf('\u0000') >= 0) { setAside(excluded.binary, path, 'binary content'); continue; }
      if (forceOut.has(path)) { setAside(excluded.user, path, 'excluded by you'); continue; }
      const webish = cls.fam === 'js' || cls.lang === 'CSS';
      const h = hashText(text);
      if (!forceIn.has(path)) {
        const rel = root && path.startsWith(root) ? path.slice(root.length) : path;
        const vd = rel.match(VENDOR_DIR);
        let vr = vd ? 'third-party folder (' + vd[2] + '/)'
          : VENDOR_NAME.test(base) ? (/^(moc|ui|qrc)_/i.test(base) ? 'Qt-generated file (moc/ui/qrc)' : 'minified or bundled file name')
          : (webish && KNOWN_LIBS.includes(libStem(base))) ? 'known library file name (' + libStem(base) + ')'
          : webish ? libraryBuildReason(text) : null;
        // shadcn/ui kit files copied in by a scaffolder (every Lovable/Vite app has ~50 of them)
        if (!vr && /(^|\/)components\/ui\/[^/]+\.(t|j)sx?$/.test(path) && /@\/lib\/utils/.test(text)) vr = 'shadcn/ui kit file (imports @/lib/utils)';
        if (vr) { setAside(excluded.vendored, path, vr); continue; }
        if (inDoxy(path)) { setAside(excluded.doxygen, path, 'Doxygen output folder'); continue; }
        const gm = text.slice(0, 1500).match(GENERATED_MARK);
        if (gm) { setAside(excluded.generated, path, 'marked as generated: "' + gm[0] + '"'); continue; }
        if (seen.has(h)) { setAside(excluded.duplicate, path, 'exact copy of ' + seen.get(h), [path, seen.get(h)]); continue; }
        const sr = webish ? suspectReason(text) : null;
        if (sr) suspects.push({ path, reason: sr });
      }
      if (!seen.has(h)) seen.set(h, path);
      if (cls.lang === 'CSS') { acc.css += text.split('\n').filter(l => l.trim()).length; continue; }
      const before = { lloc: acc.lloc, tokens: acc.tokens, decisions: acc.decisions, units: acc.units, checks: acc.checks };
      if (cls.fam === 'html') {
        const H = splitHtml(text);
        for (const p of H.parts) analyzeCode(p.code, p.lang, p.fam, acc, I, { path, line0: p.line0, handler: p.handler });
        for (const a of H.attrs) { const found = new Set(); formatsIn(a.val, found); for (const x of found) if (!acc.formats.has(x)) { acc.formats.add(x); acc.ev.formats[x] = { path, line: a.line + 1, text: a.val.slice(0, 140), type: 'attribute' }; } }
        for (const s of H.srcs) { const l = libFromUrl(s); if (l && !acc.deps.has(l)) { acc.deps.add(l); acc.ev.deps[l] = { path, line: nlCount(text, Math.max(0, text.indexOf(s))) + 1, text: s.slice(0, 140), type: 'script src' }; } }
        for (let p = 0; p < H.payloads; p++) acc.payloads.push(path);
        for (let p = 0; p < H.inlineLibs; p++) setAside(excluded.vendored, path + ' (inline library script ' + (p + 1) + ')', 'inline copy of a known library');
        acc.css += H.cssLines;
        if (H.fileInput && !acc.markers.has('File pickers')) { acc.markers.add('File pickers'); acc.mentions.delete('File pickers'); acc.ev.markers['File pickers'] = { path, line: H.fileInput.line, text: H.fileInput.text, type: 'markup' }; }
      } else if (cls.fam === 'ipynb') {
        let code = '';
        try { const nb = JSON.parse(text); for (const c of nb.cells || []) if (c.cell_type === 'code') code += (Array.isArray(c.source) ? c.source.join('') : c.source) + '\n'; } catch (e) { /* not json */ }
        analyzeCode(code.replace(/^[ \t]*[%!].*$/gm, ''), 'Python', 'py', acc, I, { path });
      } else {
        analyzeCode(text, cls.lang, cls.fam, acc, I, { path });
      }
      acc.paths.add(path);
      // v1.9: lines per file that carry anything (code or comment), for the modularity indicator
      let tloc = 0; for (const ln of text.split('\n')) if (nonWs(ln)) tloc++;
      acc.mod.files++; if (tloc < MOD_MIN) acc.mod.small++; else if (tloc > MOD_MAX) { acc.mod.big++; acc.mod.worst.push({ path, tloc }); if (acc.mod.worst.length > 40) { acc.mod.worst.sort((a, b) => b.tloc - a.tloc); acc.mod.worst.length = 10; } }
      perFile.push({ path, tloc, lang: cls.lang, lloc: acc.lloc - before.lloc, tokens: acc.tokens - before.tokens, decisions: acc.decisions - before.decisions, units: acc.units - before.units, checks: acc.checks - before.checks, hash: h, scope: scopeOf(path, setRoot), included: forceIn.has(path) || undefined });
    }
    return { measure: summarize(acc), acc, perFile, excluded, suspects };
  }

  // Each language counts up to 1, reaching 1 at LANG_MIN_TOKENS code tokens (about 50 lines; continuous, no cliff)
  function langStack(langTokens) { let s = 0; for (const [k, v] of Object.entries(langTokens)) if (k !== 'HTML' && v > 0) s += Math.min(1, v / LANG_MIN_TOKENS); return Math.round(s * 1000) / 1000; }
  function summarize(acc) {
    const payloadNames = acc.payloads.map((l, i) => 'embedded payload #' + (i + 1));
    const canon = new Map();
    for (const d of acc.deps) { const c = canonDep(d); if (c && !canon.has(c)) canon.set(c, acc.ev.deps[d]); }
    const deps = Array.from(canon.keys()).concat(payloadNames);
    const evDeps = Object.fromEntries(Array.from(canon.entries()));
    acc.payloads.forEach((p, i) => { evDeps['embedded payload #' + (i + 1)] = { path: p, line: null, text: 'encoded data line over 2,000 characters', type: 'payload' }; });
    const swmm = Object.keys(acc.swmmStage).filter(k => acc.swmmStage[k] !== 'mentioned').sort();
    const ls = langStack(acc.langTokens);
    // an import of a known library is usage too
    const depLower = new Map(Array.from(canon.keys()).map(k => [k.toLowerCase(), k]));
    for (const mk of MARKERS) {
      if (acc.markers.has(mk.name) || !mk.deps) continue;
      const hit = mk.deps.find(d => depLower.has(d));
      if (hit) { acc.markers.add(mk.name); acc.mentions.delete(mk.name); const e = evDeps[depLower.get(hit)] || {}; acc.ev.markers[mk.name] = Object.assign({}, e, { type: 'import of ' + depLower.get(hit) }); }
    }
    const markers = Array.from(acc.markers).sort();
    const st = structureOf(acc);
    return {
      bulk: acc.tokens, branches: acc.decisions, routines: acc.units, checks: acc.checks, lines: acc.lloc,
      stack: Math.round((ls + markers.length) * 1000) / 1000,
      dependencies: deps.length, formats: acc.formats.size, swmm: swmm.length,
      detail: {
        langs: acc.langs, langTokens: acc.langTokens, langStack: ls, langsCounted: Object.keys(acc.langTokens).filter(k => k !== 'HTML' && acc.langTokens[k] >= LANG_MIN_TOKENS).sort(),
        markers, mentions: Array.from(acc.mentions.keys()).filter(k => !acc.markers.has(k)).sort(),
        deps: deps.sort(), formats: Array.from(acc.formats).sort(), swmm, swmmStages: Object.assign({}, acc.swmmStage),
        evidence: { markers: Object.assign({}, acc.ev.markers, Object.fromEntries(acc.mentions)), deps: evDeps, formats: Object.assign({}, acc.ev.formats), swmm: Object.assign({}, acc.ev.swmm) },
        css: acc.css, payloads: acc.payloads.length, longLines: acc.longLines, longLineFiles: acc.longLineFiles.slice(),
        jsxTextChars: acc.jsxText, jsxFiles: Array.from(acc.jsxFiles).slice(0, 50),
        structure: st, metrics: metricsOf(acc, st, swmm), upkeep: upkeepOf(acc), processes: processCoverage(swmm).map(p => ({ key: p.key, hit: p.hit, total: p.total }))
      }
    };
  }

  // Overrides: {markers|deps|formats|swmm: {item: 'exclude'|'include'}}. 'include' promotes a mention to a signal.
  function applyOverrides(measure, ov) {
    if (!ov || !measure.detail) return measure;
    const d = measure.detail, out = JSON.parse(JSON.stringify(measure));
    const pick = (list, map, mentions) => { let l = list.filter(x => !(map && map[x] === 'exclude')); if (map) for (const [k, v] of Object.entries(map)) if (v === 'include' && !l.includes(k) && (!mentions || mentions.includes(k))) l.push(k); return l.sort(); };
    const mentionedSwmm = Object.keys(d.swmmStages || {}).filter(k => d.swmmStages[k] === 'mentioned');
    out.detail.markers = pick(d.markers || [], ov.markers, d.mentions || []);
    out.detail.deps = pick(d.deps || [], ov.deps);
    out.detail.formats = pick(d.formats || [], ov.formats);
    out.detail.swmm = pick(d.swmm || [], ov.swmm, mentionedSwmm);
    out.stack = Math.round(((d.langStack || 0) + out.detail.markers.length) * 1000) / 1000;
    out.dependencies = out.detail.deps.length; out.formats = out.detail.formats.length; out.swmm = out.detail.swmm.length;
    out.overrides = ov;
    return out;
  }

