        // if that identifier names SWMM (SWMM_NODE_DEPTH) or the file's own code does (an openswmm source file)
        let a0 = mm.index, b0 = end; while (a0 > 0 && /[\w$]/.test(hayIds[a0 - 1])) a0--; while (b0 < hayIds.length && /[\w$]/.test(hayIds[b0])) b0++;
